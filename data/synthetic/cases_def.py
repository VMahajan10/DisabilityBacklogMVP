"""Definitions of the synthetic claim files. ALL names, facilities, MRNs and events are fictional.

Each case: claimant info, documents (each a list of logical pages), and expected outcomes used by
the eval script. Expected outcomes were checked against the verbatim Blue Book 1.00 text in data/bluebook/.
listing_outcome is the set of acceptable AI "overall" calls for the best-matching expected listing
(borderline cases accept more than one). Case 5's osteosarcoma is a CAL condition normally evaluated
outside 1.00 (cancer listings), so no 1.00 listing is expected to be met; CAL drives fast-track triage.
"""


def visit(date, provider, visit_type, cc, subjective, objective, assessment, plan, vitals=None):
    page = [
        ("title", f"{visit_type} - {date}"),
        ("kv", [("Date of service", date), ("Provider", provider), ("Chief complaint", cc)]
         + ([("Vitals", vitals)] if vitals else [])),
        ("h", "Subjective"), ("p", subjective),
        ("h", "Objective / Examination"), ("p", objective),
        ("h", "Assessment"), ("p", assessment),
        ("h", "Plan"), ("p", plan),
        ("sp", 6), ("small", f"Electronically signed by {provider} on {date}."),
    ]
    return page


def imaging(date, study, indication, technique, findings, impression, radiologist, comparison="None."):
    return [
        ("title", f"Radiology Report - {study}"),
        ("kv", [("Exam date", date), ("Study", study), ("Indication", indication), ("Comparison", comparison)]),
        ("h", "Technique"), ("p", technique),
        ("h", "Findings"), ("p", findings),
        ("h", "Impression"), ("p", impression),
        ("sp", 6), ("small", f"Interpreted and electronically signed by {radiologist}, {date}."),
    ]


def function_report_pages(name, date, answers_p1, answers_p2):
    return [
        [("title", "Function Report - Adult (synthetic facsimile)"),
         ("kv", [("Claimant", name), ("Date completed", date), ("Completed by", "Claimant")]),
         ("small", "This is a fictional facsimile created for software testing. It is not an SSA form.")]
        + [x for q, a in answers_p1 for x in (("h", q), ("p", a))],
        [("title", "Function Report - Adult (continued)")] + [x for q, a in answers_p2 for x in (("h", q), ("p", a))],
    ]


